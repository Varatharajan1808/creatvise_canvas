/**
 * Shared utility functions across the canvas application.
 */

/**
 * Escapes special HTML characters to prevent XSS and formatting issues.
 */
export function escapeHtml(s: string): string {
  return s.replace(/[&<>"']/g, (c) => ({
    '&': '&amp;',
    '<': '&lt;',
    '>': '&gt;',
    '"': '&quot;',
    "'": '&#39;',
  }[c]!));
}
